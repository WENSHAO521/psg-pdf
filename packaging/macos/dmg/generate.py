#!/usr/bin/env python3
"""Regenerate the macOS DMG window files for both apps (see README.md here):

    background.svg / background.tiff / dmg-layout.DS_Store                      PSG PDF
    academic-background.svg / academic-background.tiff / academic-layout.DS_Store  PSG Academic PDF

Needs resvg and usvg on PATH and:
    pip install 'pillow>=12' ds_store==1.3.3 mac_alias==2.2.3

Runs on any OS, no Mac needed. Every output comes from this script alone, so it carries nothing
from the machine that made it: no local paths, user or disk names, dates or volume UUIDs. The
text is outlined with usvg from the OFL fonts in assets/fonts, so rendering needs no fonts.

    python3 packaging/macos/dmg/generate.py
"""

import datetime
import os
import re
import shutil
import subprocess
import sys
import tempfile

from ds_store import DSStore
from mac_alias import Alias, TargetInfo, VolumeInfo
from PIL import Image, ImageCms

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
FONTS = [os.path.join(ROOT, "assets", "fonts", f) for f in ("Inter-SemiBold.ttf", "Inter-Medium.ttf", "JetBrainsMono-Regular.ttf")]

# Keep in sync with package.sh (volume and app names) and README.md (layout).
VARIANTS = {
    "psg-pdf": {
        "volume": "PSG PDF",
        "app": "PSG PDF.app",
        "title": "PSG PDF",
        "icon": "../../../assets/app-icon/psg-pdf.svg",
        "field": "#1f3a68",
        "accent": "#d9a441",
        "prefix": "",
        "layout": "dmg-layout.DS_Store",
    },
    "psg-academic-pdf": {
        "volume": "PSG Academic PDF",
        "app": "PSG Academic PDF.app",
        "title": "PSG Academic PDF",
        "icon": "../../../assets/app-icon-academic/psg-academic-pdf.svg",
        "field": "#6e2034",
        "accent": "#d9a441",
        "prefix": "academic-",
        "layout": "academic-layout.DS_Store",
    },
}
WIDTH, HEIGHT = 660, 400  # window content, pt; the background's 1x size
TITLE_BAR = 32
ICON_SIZE = 128
PALETTE = 16  # colours in background.tiff
APP_POS, APPLICATIONS_POS = (326, 205), (574, 205)
INK, PAPER, MUTED = "#0b0b0c", "#efe9dc", "#4a4a48"
# A fixed date for the alias and the colour profile. Finder never matches it against the image
# (each build is a new volume): it finds the background by volume name and path.
FIXED_DATE = datetime.datetime(2026, 10, 8, tzinfo=datetime.timezone.utc)


def text_layer(v):
    """The variant's words, as live text; outline() turns them into paths."""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">
<text x="267" y="72" font-family="Inter" font-weight="600" font-size="32" fill="{INK}">{v["title"]}</text>
<text x="267" y="114" font-family="JetBrains Mono" font-size="10.5" fill="{MUTED}">Panorama Scholarly Group · based on PdfCraft</text>
<text x="267" y="360" font-family="Inter" font-weight="500" font-size="11.5" letter-spacing="1.6" fill="{MUTED}">DRAG ONTO APPLICATIONS TO INSTALL</text>
</svg>
"""


def outline(svg_text):
    """The drawing elements of `svg_text` with every glyph converted to a path by usvg."""
    with tempfile.TemporaryDirectory() as tmp:
        src, out = os.path.join(tmp, "in.svg"), os.path.join(tmp, "out.svg")
        with open(src, "w") as f:
            f.write(svg_text)
        args = ["usvg", "--skip-system-fonts"]
        for font in FONTS:
            args += ["--use-font-file", font]
        subprocess.run(args + [src, out], check=True)
        with open(out) as f:
            body = f.read()
    body = body[body.index(">", body.index("<svg")) + 1 : body.rindex("</svg>")]
    if "<text" in body:
        sys.exit("error: usvg left text unoutlined (fonts missing?)")
    return body.strip()


def background_svg(v):
    accent, field = v["accent"], v["field"]
    return f"""<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">
<!-- Generated by generate.py; edit the script, not this file. -->
<defs><clipPath id="panel"><rect width="232" height="400"/></clipPath></defs>
<rect width="{WIDTH}" height="{HEIGHT}" fill="{PAPER}"/>
<g clip-path="url(#panel)"><rect width="232" height="400" fill="{field}"/><g transform="translate(-134.0,-40.0)"><image href="{v["icon"]}" width="512" height="512"/></g></g>
<line x1="232.5" y1="0" x2="232.5" y2="400" stroke="{INK}" stroke-width="1.2"/>
<line x1="236.5" y1="0" x2="236.5" y2="400" stroke="{INK}" stroke-width="0.5"/>
<line x1="267" y1="88.5" x2="624" y2="88.5" stroke="{INK}" stroke-width="0.6"/>
<path d="M271.5,81.5 L276,88.5 L271.5,95.5 L267,88.5 Z" fill="{accent}"/>
<rect x="408" y="197" width="78" height="16" rx="2" fill="{accent}" fill-opacity="0.55"/><line x1="414" y1="205" x2="482" y2="205" stroke="{INK}" stroke-width="1.6"/><path d="M499.1,205.0 L486.1,211.0 L486.1,199.0 Z" fill="{INK}"/>
<line x1="267" y1="335.5" x2="624" y2="335.5" stroke="{INK}" stroke-width="0.6"/>
<g id="text">
{outline(text_layer(v))}
</g>
</svg>
"""


def render(svg, width, out):
    # The SVG's text is already outlined and no fonts are loaded, so every machine draws the
    # same pixels.
    subprocess.run(
        ["resvg", "--skip-system-fonts", "-w", str(width), svg, out],
        check=True,
    )
    with Image.open(out) as im:
        return im.convert("RGB")


def quantize(im):
    # No dithering: dither noise compresses badly and the artwork has flat fills.
    return im.quantize(PALETTE, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)


def srgb_profile():
    # LittleCMS's built-in sRGB ("No copyright, use freely"), with its creation date fixed.
    icc = bytearray(ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes())
    d = FIXED_DATE
    icc[24:36] = b"".join(v.to_bytes(2, "big") for v in (d.year, d.month, d.day, 0, 0, 0))
    if icc[84:100] != bytes(16):
        sys.exit("error: the sRGB profile has an ID; recompute it after fixing the date")
    return bytes(icc)


def write_tiff(svg, out):
    """1x (72 dpi) and 2x (144 dpi) in one TIFF, as `tiffutil -cathidpicheck` writes them."""
    with tempfile.TemporaryDirectory() as tmp:
        one, two = (
            quantize(render(svg, WIDTH * s, os.path.join(tmp, f"{s}x.png"))) for s in (1, 2)
        )
    two.encoderinfo = {"dpi": (144, 144)}  # the rest as the first page
    # Opaque 16-colour palette, Deflate: the artwork is three inks plus antialiasing, and a palette
    # keeps the file small (RGB was ~230 KB; repository assets must stay small). As PhotoCraft's.
    one.save(
        out,
        "TIFF",
        save_all=True,
        append_images=[two],
        compression="tiff_adobe_deflate",  # brand-ok: Pillow's name for TIFF compression 8 (Deflate)
        dpi=(72, 72),
        icc_profile=srgb_profile(),
    )
    with Image.open(out) as im:
        im.seek(1)
        if im.info.get("dpi") != (144, 144):
            sys.exit("error: the 2x page isn't 144 dpi (needs Pillow 12 or later)")
        strips = []
        for page in (0, 1):
            im.seek(page)
            strips += zip(im.tag_v2[273], im.tag_v2[279])  # StripOffsets, StripByteCounts
    # TIFF keeps directories and tag data on even offsets. When a strip ends on an odd one, libtiff
    # leaves the padding byte after it uninitialised, so the file changed from run to run with
    # identical pixels. Zero it: nothing refers to that byte.
    starts = {o for o, _ in strips}
    with open(out, "r+b") as f:
        for o, n in strips:
            if (o + n) % 2 and o + n not in starts:
                f.seek(o + n)
                f.write(bytes(1))


def background_alias(volume_name, tiff):
    # What Finder stores for /.background/background.tiff on the volume, minus anything about the
    # machine (dmgbuild writes the same kind of alias from a mounted image). Disk type 5 (ejectable),
    # the volume flags and the folder/file ids (25, 26) are what Finder wrote on a test image; the ids
    # are only hints, as the volume's creation date.
    volume = VolumeInfo(volume_name, FIXED_DATE, b"H+", 5, 0x0D02, b"\0\0")
    volume.posix_path = f"/Volumes/{volume_name}"
    target = TargetInfo(0, tiff, 25, 26, FIXED_DATE, b"\0\0\0\0", b"\0\0\0\0")
    target.folder_name = ".background"
    target.cnid_path = [25]
    target.carbon_path = f"{volume_name}:.background:\0{tiff}"
    target.posix_path = f"/.background/{tiff}"
    return Alias(volume=volume, target=target).to_bytes()


def write_ds_store(v, out):
    if os.path.exists(out):
        os.remove(out)
    with DSStore.open(out, "w+") as d:
        d["."]["bwsp"] = {
            "ShowStatusBar": False,
            "ShowToolbar": False,
            "ShowTabView": False,
            "ContainerShowSidebar": False,
            "ShowSidebar": False,
            "WindowBounds": f"{{{{200, 528}}, {{{WIDTH}, {HEIGHT + TITLE_BAR}}}}}",
        }
        d["."]["icvp"] = {
            "viewOptionsVersion": 1,
            "backgroundType": 2,
            "backgroundImageAlias": background_alias(v["volume"], "background.tiff"),
            "backgroundColorRed": 1.0,
            "backgroundColorGreen": 1.0,
            "backgroundColorBlue": 1.0,
            "gridOffsetX": 0.0,
            "gridOffsetY": 0.0,
            "gridSpacing": 100.0,
            "arrangeBy": "none",
            "showIconPreview": True,
            "showItemInfo": False,
            "labelOnBottom": True,
            "textSize": 16.0,
            "iconSize": float(ICON_SIZE),
        }
        d["."]["vSrn"] = ("long", 1)
        d[v["app"]]["Iloc"] = APP_POS
        d["Applications"]["Iloc"] = APPLICATIONS_POS


def main():
    for tool in ("resvg", "usvg"):
        if not shutil.which(tool):
            sys.exit(f"error: {tool} not found (cargo install resvg usvg --locked)")
    for v in VARIANTS.values():
        svg = os.path.join(HERE, f"{v['prefix']}background.svg")
        with open(svg, "w") as f:
            f.write(background_svg(v))
        write_tiff(svg, os.path.join(HERE, f"{v['prefix']}background.tiff"))
        write_ds_store(v, os.path.join(HERE, v["layout"]))


if __name__ == "__main__":
    main()
